export function getEmissionFactorById(id: string): EmissionFactor | undefined {
  return EMISSION_FACTORS.find((f) => f.id === id);
}

export function getFactorsByCategory(category: string): EmissionFactor[] {
  return EMISSION_FACTORS.filter((f) => f.category === category);
}

export function getDefaultFactorForCategory(category: string, region = 'India'): EmissionFactor {
  const matching = EMISSION_FACTORS.filter((f) => f.category === category);
  if (region === 'India') {
    const regional = matching.find((f) => f.region.toLowerCase().includes('india'));
    if (regional) return regional;
  }
  return matching[0] || EMISSION_FACTORS[0];
}
