import { ActivityRecord, EventWorkspace, Organization, Profile } from '../types';
import { calculateCategoryTotals, calculatePerPersonEmissions, calculateTotalEmissions } from './calculations';

/**
 * Generates and downloads a standards-compliant CSV file of all activity records
 */
export function exportActivitiesToCSV(activities: ActivityRecord[], filename = 'ecotrack-activities-report.csv'): void {
  const headers = [
    'Activity ID',
    'Date',
    'Category',
    'Activity Type',
    'Quantity',
    'Unit',
    'Emission Factor (kg CO2e/unit)',
    'Estimated Emissions (kg CO2e)',
    'Factor Source Citation',
    'Details / Notes',
  ];

  const rows = activities.map((act) => {
    const cleanNotes = (act.notes || '').replace(/"/g, '""');
    const source = (act.factor_source_name || 'Verified Standard Registry').replace(/"/g, '""');
    const actType = act.activity_type.replace(/_/g, ' ');

    return [
      act.id,
      act.activity_date,
      act.category,
      `"${actType}"`,
      act.quantity,
      act.unit,
      act.factor_value_used,
      act.estimated_emissions,
      `"${source}"`,
      `"${cleanNotes}"`,
    ].join(',');
  });

  const csvContent = [headers.join(','), ...rows].join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Formats data for institutional audit summary print view
 */
export function getPrintableAuditSummary(
  activities: ActivityRecord[],
  profile?: Profile,
  org?: Organization,
  event?: EventWorkspace
) {
  const totalKg = calculateTotalEmissions(activities);
  const totalTons = Math.round((totalKg / 1000) * 100) / 100;
  const categories = calculateCategoryTotals(activities);
  const participantCount = event?.actual_participants || org?.participant_count || 1;
  const perPersonKg = calculatePerPersonEmissions(totalKg, participantCount);

  return {
    title: event ? event.name : org ? org.name : 'Carbon Emissions Screening Summary',
    reportingDate: new Date().toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    }),
    organization: org?.name || 'Apex Institute of Technology & Green Innovation',
    venue: event?.venue_name || 'Campus Main Facility',
    participants: participantCount,
    totalEmissionsKg: totalKg,
    totalEmissionsTons: totalTons,
    perPersonEmissionsKg: perPersonKg,
    categories,
    activitiesCount: activities.length,
    disclaimer:
      'This report is generated by EcoTrack AI for internal sustainability screening and baseline reduction planning. Calculation factors reflect published references (CEA India CO2 Baseline Database v19, UK DEFRA 2024, US EPA eGRID, Poore & Nemecek 2018). It does not constitute ISO 14064 or GHG Protocol regulatory certification.',
  };
}
